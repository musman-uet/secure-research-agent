"""Evaluate the research agent against a single-shot RAG baseline.

Same documents, same users, same questions. The baseline is the v1
pipeline from secure-rag-m365 (one hybrid search, one extractive answer).

Metrics
  * Fact recall      share of expected facts present in the answer
  * Status accuracy  answered / partial / conflicting / insufficient as expected
  * Citation precision  cited documents that are actually relevant
  * Leaks            evidence from a document the user cannot open (every user x every question)
  * Cost             tool calls and latency per question
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

from research_agent.agent import ROOT, build_local_agent
from securerag.directory import JsonDirectory
from securerag.generation import ExtractiveGenerator
from securerag.pipeline import RagPipeline

GOLDEN = ROOT / "eval" / "golden_set.json"


def _norm(s: str) -> str:
    return s.lower().replace(",", "")


def fact_recall(answer: str, facts: list[str]) -> float | None:
    if not facts:
        return None
    a = _norm(answer)
    return sum(_norm(f) in a for f in facts) / len(facts)


def _status_ok(got: str, expected: str) -> bool:
    return got == expected


def run(out: str | None = "eval/results.md") -> int:
    questions = json.loads(GOLDEN.read_text(encoding="utf-8"))["questions"]
    manifest = json.loads((ROOT / "data" / "manifest.json").read_text(encoding="utf-8"))
    acl = {d["doc_id"]: set(d["allowed_principals"]) for d in manifest["documents"]}
    title_to_doc = {d["title"]: d["doc_id"] for d in manifest["documents"]}
    directory = JsonDirectory(ROOT / "data" / "directory.json")

    agent = build_local_agent()
    baseline = RagPipeline(agent.backend, agent.embedder, ExtractiveGenerator())

    rows, agent_scores, base_scores = [], {"recall": [], "status": [], "cprec": [], "calls": [], "ms": []}, \
        {"recall": [], "status": []}
    for q in questions:
        user = directory.get_user(q["user"])
        r = agent.run(q["question"], user)
        b = baseline.ask(q["question"], user)
        ra = fact_recall(r.summary, q["facts"])
        rb = fact_recall(b.answer, q["facts"])
        cited = {title_to_doc.get(c["title"]) for cl in r.claims for c in cl["citations"]}
        cprec = (len(cited & set(q["relevant"])) / len(cited)) if cited and q["relevant"] else None
        agent_scores["status"].append(_status_ok(r.status, q["status"]))
        base_scores["status"].append(_status_ok(b.status.value, q["status"]))
        if ra is not None:
            agent_scores["recall"].append(ra)
            base_scores["recall"].append(rb)
        if cprec is not None:
            agent_scores["cprec"].append(cprec)
        agent_scores["calls"].append(r.stats["tool_calls"])
        agent_scores["ms"].append(r.stats["latency_ms"])
        rows.append((q["id"], q["type"], q["user"], q["status"], r.status, b.status.value,
                     "-" if ra is None else f"{ra:.2f}", "-" if rb is None else f"{rb:.2f}", r.stats["tool_calls"]))

    # Security: every user x every question, every document the agent READ (not just cited).
    checks = leaks = 0
    for user in directory.all_users():
        for q in questions:
            r = agent.run(q["question"], user)
            for doc in r.stats["evidence_doc_ids"]:
                checks += 1
                if not set(user.principals) & acl[doc]:
                    leaks += 1

    mean = lambda xs: sum(xs) / len(xs) if xs else 0.0  # noqa: E731
    lines = [
        "# Evaluation: research agent vs single-shot RAG",
        "",
        f"{len(questions)} questions, 5 users, offline mode (no LLM). Generated by `python -m research_agent eval`.",
        "",
        "| Metric | Research agent | Single-shot RAG (v1) |",
        "|---|---|---|",
        f"| Fact recall (answerable questions) | **{mean(agent_scores['recall']):.2f}** | {mean(base_scores['recall']):.2f} |",
        f"| Status accuracy | **{mean(agent_scores['status']):.0%}** | {mean(base_scores['status']):.0%} |",
        f"| Citation precision | {mean(agent_scores['cprec']):.2f} | n/a |",
        f"| Tool calls per question (median) | {statistics.median(agent_scores['calls']):.0f} | 1 search |",
        f"| Latency per question (median, offline) | {statistics.median(agent_scores['ms']):.1f} ms | - |",
        "",
        f"**Permission leaks: {leaks}** across {checks} documents read by the agent (every user x every question, "
        "including documents read but not cited).",
        "",
        "| Q | Type | User | Expected | Agent | Baseline | Agent recall | Baseline recall | Tool calls |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        ok = "" if row[4] == row[3] else " ✗"
        lines.append(f"| {row[0]} | {row[1]} | {row[2]} | {row[3]} | {row[4]}{ok} | {row[5]} | {row[6]} | {row[7]} | {row[8]} |")
    report = "\n".join(lines) + "\n"
    print(report)
    if out:
        (ROOT / out).write_text(report, encoding="utf-8")
    return 1 if leaks else 0
